#!/usr/bin/env node
// Builds the single country registry used by the dashboard, the sync scripts
// and the API functions:
//   public/legacy/countries.json  (Node: lib/registry.cjs)
//   public/legacy/countries.js    (browser: window.COUNTRY_REGISTRY, loaded before config.js)
// Run: node sync/registry.js     (keyless; World Bank public API)
const fs = require('fs');
const path = require('path');
const { buildRegistry } = require('../lib/registry-build.cjs');

const OUT_DIR = path.join(__dirname, '..', 'public', 'legacy');

async function main() {
  const r = await fetch('https://api.worldbank.org/v2/country?format=json&per_page=400', {
    headers: { 'User-Agent': 'G20Dashboard-Registry/1.0' },
    signal: AbortSignal.timeout(45000),
  });
  if (!r.ok) throw new Error(`World Bank country API ${r.status}`);
  const json = await r.json();
  if (!Array.isArray(json) || !Array.isArray(json[1])) throw new Error('Unexpected World Bank country payload');
  if (json[0]?.pages > 1) throw new Error('World Bank country list spans several pages; raise per_page');
  const registry = buildRegistry(json[1]);
  const body = JSON.stringify(registry, null, 1);
  fs.writeFileSync(path.join(OUT_DIR, 'countries.json'), body + '\n');
  fs.writeFileSync(path.join(OUT_DIR, 'countries.js'),
    `// Generated by sync/registry.js from the World Bank country API. Do not edit by hand.\nwindow.COUNTRY_REGISTRY = ${body};\n`);
  console.log(`Registry written: ${registry.countries.length} countries, ${registry.aggregates.length} aggregates, ` +
    `${registry.collections.regions.length} regions, ${registry.collections.income.length} income groups`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
